"""Build the static (GitHub Pages) version of the dashboard.

Aggregates the cleaned database into docs/data.js and copies the dashboard styles,
so docs/ can be served by GitHub Pages without a Python server.
Only counts are exported – no tweet texts or user names.

Run from the repository root (after 02_cleaning.ipynb has created the cleaned database):

    python dashboard/build_static.py
"""

import json
import shutil
import sqlite3
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
DB_PATH = ROOT / "data" / "processed" / "cleaned_database.sqlite"
DOCS = ROOT / "docs"

SENTIMENTS = ["negative", "neutral", "positive"]


def main():
    if not DB_PATH.exists():
        raise FileNotFoundError(
            f"{DB_PATH} not found – run notebooks/02_cleaning.ipynb first (see README)."
        )
    conn = sqlite3.connect(DB_PATH)
    df = pd.read_sql_query(
        "SELECT airline, airline_sentiment, negativereason, tweet_created, tweet_location FROM Tweets;",
        conn,
    )
    conn.close()

    # "2015-02-24 11:35:52 -0800": keep the tweet's local date, ignore the offset
    df["date"] = df["tweet_created"].str[:10]

    dates = sorted(df["date"].unique())
    airlines = df["airline"].value_counts().index.tolist()  # fixed order by total volume
    reasons = df["negativereason"].dropna().value_counts().index.tolist()
    locations = df["tweet_location"].dropna().value_counts().index.tolist()

    def index_of(values):
        lookup = {v: i for i, v in enumerate(values)}
        return lambda v: -1 if pd.isna(v) else lookup[v]

    counts = (
        df.groupby(["date", "airline", "airline_sentiment", "negativereason", "tweet_location"], dropna=False)
        .size()
        .reset_index(name="n")
    )
    # Compact rows: [date, airline, sentiment, reason, location, count] as indices (-1 = missing)
    rows = list(zip(
        counts["date"].map(index_of(dates)),
        counts["airline"].map(index_of(airlines)),
        counts["airline_sentiment"].map(index_of(SENTIMENTS)),
        counts["negativereason"].map(index_of(reasons)),
        counts["tweet_location"].map(index_of(locations)),
        counts["n"],
    ))

    data = {
        "dates": dates,
        "airlines": airlines,
        "sentiments": SENTIMENTS,
        "reasons": reasons,
        "locations": locations,
        "rows": [[int(x) for x in row] for row in rows],
    }

    DOCS.mkdir(exist_ok=True)
    payload = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    (DOCS / "data.js").write_text(
        "// Generated by dashboard/build_static.py – do not edit by hand.\n"
        f"window.DASHBOARD_DATA = {payload};\n",
        encoding="utf-8",
    )
    shutil.copyfile(ROOT / "dashboard" / "assets" / "style.css", DOCS / "style.css")
    (DOCS / ".nojekyll").touch()  # serve the files as they are

    print(f"Wrote {DOCS / 'data.js'}: {len(rows):,} rows, {int(counts['n'].sum()):,} tweets")


if __name__ == "__main__":
    main()
